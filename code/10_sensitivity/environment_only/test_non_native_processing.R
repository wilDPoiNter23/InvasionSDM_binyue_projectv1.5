# Exercise structural native exclusions, true zeros and genuinely missing predictions.
a<-commandArgs(FALSE);script<-sub('^--file=','',grep('^--file=',a,value=TRUE))
expressions<-parse(file.path(dirname(script),'compare_non_native_processing.R'))
hit<-vapply(expressions,function(x)is.call(x)&&identical(x[[1]],as.name('<-'))&&identical(x[[2]],as.name('build')),logical(1))
stopifnot(sum(hit)==1L)
env<-new.env(parent=baseenv());eval(expressions[[which(hit)]],env)
v<-rbind(c(.8,NA,.6,NA),c(NA,0,NA,.4),rep(NA_real_,4),rep(NA_real_,4))
native<-rbind(c(TRUE,FALSE,FALSE,TRUE),rep(FALSE,4),rep(TRUE,4),rep(FALSE,4))
d<-env$build('test',v,native)
stopifnot(identical(d$counts$native,c(2,0,4,0)),identical(d$counts$observed,c(1,2,0,0)),identical(d$counts$missing,c(1,2,0,4)))
stopifnot(isTRUE(all.equal(d$values$coverage_adjusted,c(.2,.2,0,NA_real_))))
stopifnot(isTRUE(all.equal(d$values$alien_mean,c(.6,.2,NA_real_,NA_real_))))
stopifnot(isTRUE(all.equal(d$values$fixed_lower,c(.15,.1,0,0))))
stopifnot(isTRUE(all.equal(d$values$fixed_upper,c(.4,.6,0,1))))
stopifnot(isTRUE(all.equal(d$values$strict_fixed,c(NA_real_,NA_real_,0,NA_real_))))
shared<-is.finite(v);shared[1,3]<-FALSE
p<-env$build('paired',v,native,shared)
stopifnot(p$counts$observed[1]==0,p$counts$missing[1]==2,is.na(p$values$alien_mean[1]))
hash_hit<-vapply(expressions,function(x)is.call(x)&&identical(x[[1]],as.name('<-'))&&identical(x[[2]],as.name('file_hash')),logical(1))
env$digest<-digest::digest;env$c<-data.frame(value=1);eval(expressions[[which(hash_hit)]],env)
path<-tempfile();writeBin(charToRaw('abc'),path)
stopifnot(identical(env$file_hash(path),'ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad'))
unlink(path)
cat('PASS native, zero, missing and paired membership tests\n')
